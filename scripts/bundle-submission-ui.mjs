import fs from 'node:fs';
import path from 'node:path';
import { build } from 'esbuild';
import { root } from './sdk.mjs';

// 交付完整依赖闭包；入口只下载清单内的固定字节，不在用户机器安装 npm 包。
const result = await build({
    absWorkingDir: root,
    stdin: { contents: "export { intro, outro, cancel, text, select, multiselect, note, log, spinner, isCancel, SELECT_INSTRUCTIONS, MULTISELECT_INSTRUCTIONS } from '@clack/prompts';", resolveDir: root },
    bundle: true, platform: 'node', format: 'esm', target: 'node24',
    write: false, metafile: true, legalComments: 'inline',
    plugins: [{ name: 'submission-prompts', setup(builder) {
        builder.onLoad({ filter: /[\\/]@clack[\\/](prompts|core)[\\/]dist[\\/]index\.mjs$/ }, ({ path: file }) => {
            let source = fs.readFileSync(file, 'utf8');
            // 补充空选文案与加载取消回调；取消交回向导清理，不从第三方组件直接退出进程。
            const patches = file.includes(`${path.sep}prompts${path.sep}`) ? [
                ['styleText("dim", "none")', 'styleText("dim", i.emptyLabel ?? "none")'],
                ['M = block({ output: n })', 'M = block({ input: I.input, output: n, onCancel: i })'],
            ] : [
                ['hideCursor: n = true\n', 'hideCursor: n = true,\n  onCancel\n'],
                ['n && r.write(cursor.show), process.exit(0);', 'n && r.write(cursor.show), onCancel ? onCancel() : process.exit(0);'],
            ];
            for (const [before, after] of patches) {
                if (source.split(before).length !== 2) throw new Error('CLACK_PATCH_CHANGED');
                source = source.replace(before, after);
            }
            return { contents: source, loader: 'js' };
        });
    } }],
});
const packages = [...new Set(Object.keys(result.metafile.inputs).map(file =>
    /^(node_modules\/(?:@[^/]+\/)?[^/]+)\//u.exec(file)?.[1]).filter(Boolean))].sort();
const notices = packages.map(directory => {
    const folder = path.join(root, directory);
    const metadata = JSON.parse(fs.readFileSync(path.join(folder, 'package.json'), 'utf8'));
    const license = fs.readdirSync(folder).find(name => /^licen[cs]e(?:\.(?:md|txt))?$/iu.test(name));
    if (!license) throw new Error('BUNDLE_LICENSE_MISSING');
    return `${metadata.name}@${metadata.version}\n${fs.readFileSync(path.join(folder, license), 'utf8').trim()}`;
}).join('\n\n');
const bytes = '/*\nGenerated by npm run bundle:ui.\n\n' + notices.replaceAll('*/', '* /') + '\n*/\n' + result.outputFiles[0].text;
const destination = path.join(root, 'scripts/vendor/clack-prompts.mjs');
if (process.argv.includes('--check')) {
    if (fs.readFileSync(destination, 'utf8') !== bytes) throw new Error('SUBMISSION_UI_BUNDLE_CHANGED');
} else {
    fs.mkdirSync(path.dirname(destination), { recursive: true });
    fs.writeFileSync(destination, bytes, 'utf8');
}
